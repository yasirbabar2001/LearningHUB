function normalize(s: string): string {
  return s
    .toLowerCase()
    .replace(/[\u2013\u2014-]/g, "-")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

const map = new Map<string, Entry>(rows.map(([l, region, wing]) => [normalize(l), { region, wing }]));

export function regionWingForLocation(locationName: string): Entry | null {
  return map.get(normalize(locationName)) ?? null;
}
